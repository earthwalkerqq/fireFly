#ifndef FIREFLY_OPENCL_H
#define FIREFLY_OPENCL_H

#include <stddef.h>

#include "triangulation.h"
#include "common.h"

/*
 * Инфраструктура гетерогенных вычислений на OpenCL.
 *
 * Модуль предоставляет средства построения гетерогенной вычислительной
 * системы: обнаружение платформ и устройств, выбор устройства (с
 * предпочтением GPU), создание контекста и очереди команд, сборку
 * вычислительных ядер и выполнение расчётов на выбранном устройстве.
 *
 * Поддержка OpenCL включается на этапе сборки флагом `make OPENCL=1`
 * (определяет макрос USE_OPENCL). Если проект собран без этого флага
 * либо подходящее устройство не найдено, все функции возвращают признак
 * недоступности, и вызывающий код выполняет расчёт на CPU. Таким
 * образом, наличие OpenCL не является обязательным для работы проекта.
 */

/**
 * @brief Сообщает, собран ли проект с поддержкой OpenCL.
 * @return 1, если поддержка OpenCL включена на этапе сборки, иначе 0.
 */
int openclAvailable(void);

/**
 * @brief Инициализирует гетерогенную вычислительную систему.
 * @details
 * Перебирает доступные платформы OpenCL, выбирает устройство (сначала
 * среди GPU, затем среди CPU), создаёт контекст и очередь команд,
 * загружает и собирает вычислительные ядра.
 * @return 1 при успешной инициализации, 0 при ошибке либо отсутствии
 *   поддержки OpenCL в данной сборке.
 */
int openclInit(void);

/**
 * @brief Освобождает все ресурсы OpenCL.
 */
void openclShutdown(void);

/**
 * @brief Печатает сведения о выбранном вычислительном устройстве.
 */
void openclPrintDevice(void);

/**
 * @brief Классифицирует треугольники по критериям безопасности на
 *   устройстве OpenCL.
 * @details
 * Для каждого треугольника вычисляется предикат корректности: высота
 * рельефа во всех вершинах определена, превышение каждой вершины над
 * рельефом не больше @p maxHeight, уклон не превышает @p maxSlope.
 * Результат записывается в @p out (1 — корректен, 0 — некорректен).
 *
 * @param tri        Массив треугольников.
 * @param countTri   Количество треугольников.
 * @param pts        Массив вершин, на которые ссылаются треугольники.
 * @param countPts   Количество вершин.
 * @param maxHeight  Предельное превышение точки над рельефом.
 * @param maxSlope   Предельный уклон (тангенс угла наклона).
 * @param flatTol    Допуск «плоскостности»: треугольник с перепадом высот
 *   вершин не больше @p flatTol считается ровным независимо от размера.
 * @param[out] out   Массив результатов размера @p countTri.
 * @return 1 при успешном выполнении на устройстве OpenCL, 0 при ошибке
 *   либо недоступности OpenCL (вызывающий код должен выполнить расчёт
 *   на CPU).
 */
int openclClassifyTriangles(const Triangle *tri, size_t countTri,
                            const point_t *pts, size_t countPts,
                            double maxHeight, double maxSlope,
                            double flatTol, unsigned char *out);

#endif
